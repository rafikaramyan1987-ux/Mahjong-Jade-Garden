"""
Extra glyphs for Polish, Turkish (Latin Extended) and Russian (Cyrillic), cut down to exactly the characters the
translations use, so the single-file builds stay small. Run after changing src/i18n/*.json:
  pip install fonttools brotli && python3 scripts/fonts-ext.py
-> src/assets/fonts/*.woff2 and src/ui/fonts-ext.css (@font-face rules with unicode-range: only used when needed)
"""
import glob, io, json, os
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FS = os.path.join(ROOT, 'node_modules', '@fontsource')
OUT = os.path.join(ROOT, 'src', 'assets', 'fonts')
os.makedirs(OUT, exist_ok=True)

chars = set()
for f in glob.glob(os.path.join(ROOT, 'src', 'i18n', '*.json')):
    for v in json.load(open(f, encoding='utf-8')).values():
        chars.update(v)
# the latin subset that is always loaded covers these
def in_latin(c):
    o = ord(c)
    return o <= 0xFF or 0x2000 <= o <= 0x206F or o in (0x131, 0x152, 0x153, 0x2BB, 0x2BC, 0x2C6, 0x2DA, 0x2DC, 0x20AC, 0x2122, 0x2212, 0x2215)
extra = sorted(c for c in chars if not in_latin(c))
groups = {'ext': [c for c in extra if ord(c) < 0x400], 'cyr': [c for c in extra if 0x400 <= ord(c) < 0x530]}
# both cases of every letter (the UI uppercases a few labels)
for k in groups:
    s = set(groups[k])
    for c in list(s):
        s.update(c.upper() + c.lower())
    groups[k] = sorted(c for c in s if not in_latin(c) and len(c) == 1)

FAMILIES = [('Source Sans 3', 'source-sans-3', 'ss3', [400, 600, 700]), ('Lora', 'lora', 'lora', [600, 700])]
css = ['/* generated by scripts/fonts-ext.py: Polish / Turkish / Russian glyphs used by the translations */']
total = 0
for fam, pkg, short, weights in FAMILIES:
    for w in weights:
        for g, src_sub in (('ext', 'latin-ext'), ('cyr', 'cyrillic')):
            cs = groups[g]
            if not cs:
                continue
            src = os.path.join(FS, pkg, 'files', f'{pkg}-{src_sub}-{w}-normal.woff2')
            font = TTFont(src)
            opts = subset.Options()
            opts.flavor = 'woff2'
            opts.layout_features = ['kern', 'liga']
            opts.name_IDs = []
            opts.notdef_outline = False
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=[ord(c) for c in cs])
            sub.subset(font)
            name = f'{short}-{g}-{w}.woff2'
            buf = io.BytesIO()
            font.flavor = 'woff2'
            font.save(buf)
            open(os.path.join(OUT, name), 'wb').write(buf.getvalue())
            total += len(buf.getvalue())
            rng = ','.join(f'U+{ord(c):04X}' for c in cs)
            css.append(f"@font-face{{font-family:'{fam}';font-style:normal;font-display:swap;font-weight:{w};src:url(../assets/fonts/{name}) format('woff2');unicode-range:{rng}}}")
open(os.path.join(ROOT, 'src', 'ui', 'fonts-ext.css'), 'w').write('\n'.join(css) + '\n')
print(f'{len(groups["ext"])} latin-ext + {len(groups["cyr"])} cyrillic glyphs, {total / 1024:.1f} KB of fonts')
